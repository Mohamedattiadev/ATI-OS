/* Manual chrome: theme toggle, mobile sidebar, heading anchors, search.
   No dependencies, no network. search-index.js is generated by
   docs/build-index.py and loaded before this file. */

(function () {
  'use strict';

  // ---- theme -------------------------------------------------------------
  var root = document.documentElement;
  var stored = null;
  try { stored = localStorage.getItem('qd-theme'); } catch (e) {}
  if (stored === 'light' || stored === 'dark') root.setAttribute('data-theme', stored);

  function currentTheme() {
    var t = root.getAttribute('data-theme');
    if (t) return t;
    return window.matchMedia && window.matchMedia('(prefers-color-scheme: light)').matches
      ? 'light' : 'dark';
  }

  function paintToggle(btn) {
    btn.textContent = currentTheme() === 'dark' ? 'Light' : 'Dark';
    btn.setAttribute('aria-label', 'Switch to ' + (currentTheme() === 'dark' ? 'light' : 'dark') + ' theme');
  }

  var toggle = document.getElementById('theme-toggle');
  if (toggle) {
    paintToggle(toggle);
    toggle.addEventListener('click', function () {
      var next = currentTheme() === 'dark' ? 'light' : 'dark';
      root.setAttribute('data-theme', next);
      try { localStorage.setItem('qd-theme', next); } catch (e) {}
      paintToggle(toggle);
    });
  }

  // ---- mobile sidebar ----------------------------------------------------
  var menu = document.getElementById('menu-toggle');
  var sidebar = document.querySelector('.sidebar');
  if (menu && sidebar) {
    menu.addEventListener('click', function () {
      sidebar.classList.toggle('open');
    });
    sidebar.addEventListener('click', function (e) {
      if (e.target.tagName === 'A') sidebar.classList.remove('open');
    });
  }

  // ---- heading anchors ---------------------------------------------------
  var hs = document.querySelectorAll('main h2[id], main h3[id]');
  for (var i = 0; i < hs.length; i++) {
    var a = document.createElement('a');
    a.className = 'anchor';
    a.href = '#' + hs[i].id;
    a.textContent = '#';
    a.setAttribute('aria-hidden', 'true');
    hs[i].appendChild(a);
  }

  // ---- search ------------------------------------------------------------
  var input = document.getElementById('search-input');
  var out = document.getElementById('search-results');
  var idx = window.SEARCH_INDEX || [];
  if (!input || !out) return;

  var sel = -1;
  var rows = [];

  function score(entry, terms) {
    var t = entry.t.toLowerCase();
    var b = entry.b.toLowerCase();
    var s = 0;
    for (var i = 0; i < terms.length; i++) {
      var q = terms[i];
      if (t.indexOf(q) === 0) s += 12;
      else if (t.indexOf(q) !== -1) s += 8;
      else if (b.indexOf(q) !== -1) s += 2;
      else return -1;
    }
    return s;
  }

  function render(list) {
    out.innerHTML = '';
    rows = [];
    sel = -1;
    if (!list.length) {
      var d = document.createElement('div');
      d.className = 'empty';
      d.textContent = 'No match.';
      out.appendChild(d);
      out.classList.add('open');
      return;
    }
    for (var i = 0; i < list.length; i++) {
      var e = list[i];
      var a = document.createElement('a');
      a.href = e.u;
      a.innerHTML = '';
      var strong = document.createElement('span');
      strong.textContent = e.t;
      var small = document.createElement('span');
      small.className = 'r-page';
      small.textContent = e.p;
      a.appendChild(strong);
      a.appendChild(small);
      out.appendChild(a);
      rows.push(a);
    }
    out.classList.add('open');
  }

  function run() {
    var q = input.value.trim().toLowerCase();
    if (q.length < 2) { out.classList.remove('open'); return; }
    var terms = q.split(/\s+/);
    var hits = [];
    for (var i = 0; i < idx.length; i++) {
      var s = score(idx[i], terms);
      if (s > 0) hits.push([s, i, idx[i]]);
    }
    hits.sort(function (a, b) { return b[0] - a[0] || a[1] - b[1]; });
    render(hits.slice(0, 25).map(function (h) { return h[2]; }));
  }

  function move(d) {
    if (!rows.length) return;
    if (sel >= 0) rows[sel].classList.remove('sel');
    sel = (sel + d + rows.length) % rows.length;
    rows[sel].classList.add('sel');
    rows[sel].scrollIntoView({ block: 'nearest' });
  }

  input.addEventListener('input', run);
  input.addEventListener('focus', run);
  input.addEventListener('keydown', function (e) {
    if (e.key === 'ArrowDown') { e.preventDefault(); move(1); }
    else if (e.key === 'ArrowUp') { e.preventDefault(); move(-1); }
    else if (e.key === 'Enter') {
      if (sel >= 0 && rows[sel]) { e.preventDefault(); window.location.href = rows[sel].href; }
    } else if (e.key === 'Escape') { out.classList.remove('open'); input.blur(); }
  });

  document.addEventListener('click', function (e) {
    if (!out.contains(e.target) && e.target !== input) out.classList.remove('open');
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === '/' && document.activeElement !== input &&
        ['INPUT', 'TEXTAREA'].indexOf(document.activeElement.tagName) === -1) {
      e.preventDefault();
      input.focus();
      input.select();
    }
  });
})();
