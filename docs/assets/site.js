/* ============================================================================
   ATI-OS manual — page behaviour.

   Everything here is an enhancement. With JavaScript off you still get the
   full left navigation, the content, and working anchor links; you lose the
   right-hand contents column, the search box and the copy buttons.

   No dependencies, no network. search-index.js is generated by
   docs/build-index.py and loaded before this file.
   ========================================================================= */

(function () {
  'use strict';

  var root = document.documentElement;
  root.classList.remove('no-js');

  var reduceMotion = window.matchMedia &&
    window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* --- theme ------------------------------------------------------------ */

  var stored = null;
  try { stored = localStorage.getItem('qd-theme'); } catch (e) {}
  if (stored === 'light' || stored === 'dark') root.setAttribute('data-theme', stored);

  function currentTheme() {
    return root.getAttribute('data-theme') ||
      (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches
        ? 'dark' : 'light');
  }

  var toggle = document.getElementById('theme-toggle');

  // Which of the two icons is visible is decided in CSS from the active
  // theme, so this only has to keep the accessible name in step -- and it
  // must not touch textContent, which would delete both <svg> children.
  // The markup ships the vaguer "Switch colour theme", because with this file
  // blocked nothing can know which way round the button is pointing; naming a
  // direction there would be wrong half the time.
  function paintToggle() {
    if (!toggle) return;
    var dark = currentTheme() === 'dark';
    toggle.setAttribute('aria-label', 'Switch to ' + (dark ? 'light' : 'dark') + ' theme');
  }
  paintToggle();

  if (toggle) {
    toggle.addEventListener('click', function () {
      var next = currentTheme() === 'dark' ? 'light' : 'dark';
      root.setAttribute('data-theme', next);
      try { localStorage.setItem('qd-theme', next); } catch (e) {}
      paintToggle();
    });
  }

  // Follow the system while the reader has not chosen for themselves.
  if (window.matchMedia) {
    var mq = window.matchMedia('(prefers-color-scheme: dark)');
    var onScheme = function () { if (!root.hasAttribute('data-theme')) paintToggle(); };
    if (mq.addEventListener) mq.addEventListener('change', onScheme);
    else if (mq.addListener) mq.addListener(onScheme);
  }

  /* --- navigation drawer ------------------------------------------------ */

  var menu = document.getElementById('menu-toggle');
  var sidebar = document.querySelector('.sidebar');
  var scrim = null;

  function setDrawer(open) {
    if (!sidebar || !menu) return;
    sidebar.classList.toggle('open', open);
    menu.setAttribute('aria-expanded', open ? 'true' : 'false');
    menu.setAttribute('aria-label', (open ? 'Close' : 'Open') + ' navigation');
    if (scrim) scrim.classList.toggle('on', open);
    document.body.style.overflow = open ? 'hidden' : '';
  }

  if (menu && sidebar) {
    scrim = document.createElement('div');
    scrim.className = 'scrim';
    scrim.setAttribute('aria-hidden', 'true');
    document.body.appendChild(scrim);

    menu.addEventListener('click', function () {
      setDrawer(!sidebar.classList.contains('open'));
    });
    scrim.addEventListener('click', function () { setDrawer(false); });
    sidebar.addEventListener('click', function (e) {
      if (e.target.closest && e.target.closest('a')) setDrawer(false);
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && sidebar.classList.contains('open')) {
        setDrawer(false);
        menu.focus();
      }
    });
  }

  /* --- heading permalinks ----------------------------------------------- */

  var headings = document.querySelectorAll('main h2[id], main h3[id]');
  Array.prototype.forEach.call(headings, function (h) {
    var a = document.createElement('a');
    a.className = 'anchor';
    a.href = '#' + h.id;
    a.textContent = '#';
    a.setAttribute('aria-label', 'Link to this section');
    h.appendChild(a);
  });

  /* --- on this page ------------------------------------------------------
     Generated from the page itself. A hand-written contents list drifts the
     moment a heading is renamed, and does it silently. */

  var toc = document.getElementById('toc');
  var tops = document.querySelectorAll('main h2[id]');

  if (toc && tops.length > 1) {
    Array.prototype.forEach.call(tops, function (h) {
      var text = '';
      Array.prototype.forEach.call(h.childNodes, function (n) {
        if (n.nodeType === 3) text += n.nodeValue;
        else if (n.nodeType === 1 && n.className !== 'anchor') text += n.textContent;
      });
      var li = document.createElement('li');
      var link = document.createElement('a');
      link.href = '#' + h.id;
      link.textContent = text.trim() || h.id;
      li.appendChild(link);
      toc.appendChild(li);
    });

    var tocLinks = toc.querySelectorAll('a');
    var panel = toc.parentNode && toc.parentNode.parentNode;
    var active = -1;

    var spy = function () {
      var headerRem = parseFloat(
        getComputedStyle(root).getPropertyValue('--header-h')) || 3.25;
      var edge = (headerRem * 16) + 40;

      var best = 0;
      for (var i = 0; i < tops.length; i++) {
        if (tops[i].getBoundingClientRect().top <= edge) best = i;
      }
      // At the very bottom, mark the last section however short it is.
      if (window.innerHeight + window.scrollY >= document.body.scrollHeight - 4) {
        best = tops.length - 1;
      }
      if (best === active) return;
      if (active >= 0 && tocLinks[active]) tocLinks[active].classList.remove('here');
      if (tocLinks[best]) tocLinks[best].classList.add('here');
      active = best;

      // Keep the marker in view when the contents list is long enough to scroll.
      if (panel && panel.scrollHeight > panel.clientHeight + 4 && tocLinks[best]) {
        var r = tocLinks[best].getBoundingClientRect();
        var p = panel.getBoundingClientRect();
        if (r.top < p.top + 8 || r.bottom > p.bottom - 8) {
          tocLinks[best].scrollIntoView({
            block: 'nearest',
            behavior: reduceMotion ? 'auto' : 'smooth'
          });
        }
      }
    };

    var pending = false;
    var onScroll = function () {
      if (pending) return;
      pending = true;
      window.requestAnimationFrame(function () { spy(); pending = false; });
    };
    window.addEventListener('scroll', onScroll, { passive: true });
    window.addEventListener('resize', onScroll, { passive: true });
    spy();
  } else if (toc) {
    var empty = toc.parentNode && toc.parentNode.parentNode;
    if (empty) empty.style.display = 'none';
  }

  /* --- copy buttons on code blocks -------------------------------------- */

  if (navigator.clipboard) {
    var blocks = document.querySelectorAll('main pre');
    Array.prototype.forEach.call(blocks, function (pre) {
      var wrap = document.createElement('div');
      wrap.className = 'codeblock';
      pre.parentNode.insertBefore(wrap, pre);
      wrap.appendChild(pre);

      var btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'copy';
      btn.textContent = 'Copy';
      btn.setAttribute('aria-label', 'Copy code to clipboard');
      wrap.appendChild(btn);

      var timer = null;
      btn.addEventListener('click', function () {
        navigator.clipboard.writeText(pre.innerText.replace(/\s+$/, '')).then(function () {
          btn.textContent = 'Copied';
          btn.classList.add('done');
          clearTimeout(timer);
          timer = setTimeout(function () {
            btn.textContent = 'Copy';
            btn.classList.remove('done');
          }, 1600);
        }, function () {
          btn.textContent = 'Press Ctrl+C';
          clearTimeout(timer);
          timer = setTimeout(function () { btn.textContent = 'Copy'; }, 2200);
        });
      });
    });
  }

  /* --- search ------------------------------------------------------------ */

  var input = document.getElementById('search-input');
  var out = document.getElementById('search-results');
  var idx = window.SEARCH_INDEX || [];
  if (!input || !out) return;

  var rows = [];
  var sel = -1;

  function score(entry, terms) {
    var t = entry.t.toLowerCase();
    var b = entry.b.toLowerCase();
    var total = 0;
    for (var i = 0; i < terms.length; i++) {
      var q = terms[i];
      if (t === q) total += 20;
      else if (t.indexOf(q) === 0) total += 12;
      else if (t.indexOf(q) !== -1) total += 8;
      else if (b.indexOf(q) !== -1) total += 2;
      else return -1;
    }
    return total;
  }

  function select(i) {
    if (sel >= 0 && rows[sel]) rows[sel].classList.remove('sel');
    sel = i;
    if (sel >= 0 && rows[sel]) {
      rows[sel].classList.add('sel');
      rows[sel].scrollIntoView({ block: 'nearest' });
    }
  }

  function render(list) {
    out.textContent = '';
    rows = [];
    sel = -1;

    if (!list.length) {
      var d = document.createElement('div');
      d.className = 'empty';
      d.textContent = 'No match in this manual.';
      out.appendChild(d);
      out.classList.add('open');
      return;
    }

    list.forEach(function (e) {
      var a = document.createElement('a');
      a.href = e.u;
      var t = document.createElement('span');
      t.className = 'r-title';
      t.textContent = e.t;
      a.appendChild(t);
      // A page's own top heading repeats the page name; do not say it twice.
      if (e.t !== e.p) {
        var p = document.createElement('span');
        p.className = 'r-page';
        p.textContent = e.p;
        a.appendChild(p);
      }
      a.addEventListener('mouseenter', function () { select(rows.indexOf(a)); });
      out.appendChild(a);
      rows.push(a);
    });
    out.classList.add('open');
  }

  function run() {
    var q = input.value.trim().toLowerCase();
    if (q.length < 2) { out.classList.remove('open'); return; }
    var terms = q.split(/\s+/);
    var hits = [];
    for (var i = 0; i < idx.length; i++) {
      var s = score(idx[i], terms);
      if (s > 0) hits.push([s, i, idx[i]]);
    }
    hits.sort(function (a, b) { return b[0] - a[0] || a[1] - b[1]; });
    render(hits.slice(0, 25).map(function (h) { return h[2]; }));
  }

  input.addEventListener('input', run);
  input.addEventListener('focus', run);

  input.addEventListener('keydown', function (e) {
    if (e.key === 'ArrowDown') {
      e.preventDefault();
      if (rows.length) select((sel + 1) % rows.length);
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      if (rows.length) select((sel - 1 + rows.length) % rows.length);
    } else if (e.key === 'Enter') {
      if (sel >= 0 && rows[sel]) { e.preventDefault(); window.location.href = rows[sel].href; }
    } else if (e.key === 'Escape') {
      out.classList.remove('open');
      input.blur();
    }
  });

  document.addEventListener('click', function (e) {
    if (!out.contains(e.target) && e.target !== input) out.classList.remove('open');
  });

  // "/" focuses the search box, the way it does in most documentation.
  document.addEventListener('keydown', function (e) {
    if (e.key !== '/' || e.metaKey || e.ctrlKey || e.altKey) return;
    var el = document.activeElement;
    var tag = el ? el.tagName : '';
    if (tag === 'INPUT' || tag === 'TEXTAREA' || (el && el.isContentEditable)) return;
    e.preventDefault();
    input.focus();
    input.select();
  });
})();
