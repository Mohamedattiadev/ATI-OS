# ---- Theme lookup + pywal ----
# theme-apply writes ~/.cache/qtile/theme_mode with the selected mode.
# active_palette() returns the matching 9-slot palette. Fallback: DoomOne.
# Wal mode reads ~/.cache/wal/colors.json and prefers the bright color
# variants (color9-14) so bar accents stay visible on dim wallpapers.

def _hex_to_hsv(hx):
    r = int(hx[1:3], 16) / 255.0
    g = int(hx[3:5], 16) / 255.0
    b = int(hx[5:7], 16) / 255.0
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    if d == 0:
        h = 0.0
    elif mx == r:
        h = (60 * ((g - b) / d) + 360) % 360
    elif mx == g:
        h = 60 * ((b - r) / d) + 120
    else:
        h = 60 * ((r - g) / d) + 240
    return h


def _hex_to_sat(hx):
    import colorsys
    r = int(hx[1:3], 16) / 255.0
    g = int(hx[3:5], 16) / 255.0
    b = int(hx[5:7], 16) / 255.0
    return colorsys.rgb_to_hsv(r, g, b)[1]


def _wal_palette():
    """Build a 9-slot palette from pywal cache.

    Two fallback triggers force DoomOne accents (keeping wal bg/fg):
      - Hue spread across color9-14 < 60 degrees (monochromatic image).
      - Mean saturation < 0.25 (washed-out image with no real color to
        extract — WAL_AUDIT_REPORT.md sample shows ~12% of wallpapers
        hit this even when the hue spread looks fine).
    """
    import json, os
    try:
        with open(os.path.expanduser("~/.cache/wal/colors.json")) as f:
            w = json.load(f)
        s = w["special"]
        c = w["colors"]
        accents = [c[f"color{i}"] for i in range(9, 15)]
        hues = [_hex_to_hsv(a) for a in accents]
        sats = [_hex_to_sat(a) for a in accents]
        spread = max(hues) - min(hues)
        sat_mean = sum(sats) / len(sats)
        bg, fg = s["background"], s["foreground"]
        if spread < 60 or sat_mean < 0.25:
            return [
                [bg, bg],
                [fg, fg],
                DoomOne[2],
                DoomOne[3],
                DoomOne[4],
                DoomOne[5],
                DoomOne[6],
                DoomOne[7],
                DoomOne[8],
            ]
        # Semantic slot mapping so widgets always highlight with the
        # wallpaper's DOMINANT hue (slot 7 = most-used foreground).
        # Precompile writes color9=urgent, color10=main/dominant,
        # color11=warm-fill, color12=cool-fill, color13=complement,
        # color14=info/cyan.
        # Widget contract inherited from DoomOne:
        #   [2] bg_alt  [3] urgent-red  [4] secondary  [5] floating-mark
        #   [6] focused-mark  [7] main-accent  [8] info/high-vis
        pick = [
            bg,
            fg,
            c["color8"],      # bg_alt
            c["color9"],      # urgent
            c["color12"],     # secondary (cool-fill) for inactive borders
            c["color13"],     # complement for V-floating markup
            c["color12"],     # cool for F-focused markup
            c["color10"],     # DOMINANT — main accent
            c["color14"],     # info/cyan — volume, GroupBox active
        ]
        return [[h, h] for h in pick]
    except Exception:
        return None


